SEARCH_FIELDS = ("title", "url", "author", "note", "text")

def _like_pattern(word: str) -> str:
    escaped = word.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
    return f"%{escaped}%"

SORTS = {
    "newest": "b.created_at DESC, b.id DESC",
    "oldest": "b.created_at ASC, b.id ASC",
    "title": "lower(COALESCE(b.title, b.url)) ASC, b.id ASC",
    "saved": "b.id DESC",   # order of saving, for the home page
}

def list_bookmarks(q: str | None = None, platform: str | None = None, category_id: int | None = None,
                   kind: str | None = None, sort: str = "newest", limit: int | None = None) -> list[dict]:
    """Bookmarks matching every given filter. For `q`, every word must appear (case-insensitive
    for ASCII) in at least one text field. `kind` is paper, post or article (see kind_of)."""
    like = "ILIKE" if is_postgres() else "LIKE"   # Postgres LIKE is case-sensitive
    clauses, params = [], []
    for word in (q or "").split():
        clauses.append("(" + " OR ".join(f"b.{f} {like} ? ESCAPE '\\'" for f in SEARCH_FIELDS) + ")")
        params.extend([_like_pattern(word)] * len(SEARCH_FIELDS))
    if platform:
        clauses.append("b.platform = ?")
        params.append(platform)
    if category_id is not None:
        clauses.append("b.category_id = ?")
        params.append(category_id)
    if kind:
        if kind not in KINDS:
            raise ValueError(f"kind must be one of {', '.join(KINDS)}")
        if kind == "article":
            special = [p for ps in KIND_PLATFORMS.values() for p in ps]
            clauses.append(f"(b.platform IS NULL OR b.platform NOT IN ({', '.join('?' * len(special))}))")
            params.extend(special)
        else:
            clauses.append(f"b.platform IN ({', '.join('?' * len(KIND_PLATFORMS[kind]))})")
            params.extend(KIND_PLATFORMS[kind])
    where = "WHERE " + " AND ".join(clauses) if clauses else ""
    sql = f"{ITEM_SELECT} {where} ORDER BY {SORTS[sort]}"
    if limit is not None:
        sql += " LIMIT ?"
        params.append(max(int(limit), 0))
    with conn() as c:
        return [_item(r) for r in c.execute(sql, params)]

def search(query: str, limit: int = 20, platform: str | None = None) -> list[dict]:
    """Every word must appear (case-insensitive for ASCII) in at least one text field. Newest first."""
    return list_bookmarks(q=query, platform=platform, limit=limit)

# --- shelves (categories) ------------------------------------------------------

class ShelfError(ValueError):
    """A shelf change the user asked for that isn't allowed; the message says why."""

class DuplicateShelf(ShelfError):
    pass

class ShelfNotFound(LookupError):
    pass

def _is_unique_violation(exc: Exception) -> bool:
    return isinstance(exc, sqlite3.IntegrityError) or type(exc).__name__ == "UniqueViolation"

def _check_name_free(c, name: str, exclude_id: int | None = None):
    # casefold in Python: SQLite's lower() only folds ASCII.
    for r in c.execute("SELECT id, name FROM categories"):
        if r["id"] != exclude_id and r["name"].casefold() == name.casefold():
            raise DuplicateShelf(f"There's already a shelf named “{r['name']}”")

def list_categories() -> list[dict]:
    """Shelves in order, each with its item count and is_fallback ("Other")."""
    with conn() as c:
        other = _fallback_id(c)
        rows = [dict(r) for r in c.execute(
            """SELECT cat.id, cat.name, cat.description, cat.position, cat.created_at, COUNT(b.id) AS count
               FROM categories cat LEFT JOIN bookmarks b ON b.category_id = cat.id
               GROUP BY cat.id, cat.name, cat.description, cat.position, cat.created_at
               ORDER BY cat.position, cat.id"""
        )]
    for r in rows:
        r["is_fallback"] = r["id"] == other
    return rows

def item_totals() -> dict:
    """{"all": every bookmark, "unsorted": bookmarks not on a shelf yet}."""
    with conn() as c:
        r = c.execute("SELECT COUNT(*) AS total, COUNT(category_id) AS shelved FROM bookmarks").fetchone()
    return {"all": r["total"], "unsorted": r["total"] - r["shelved"]}

def get_category(cid: int) -> dict | None:
    with conn() as c:
        r = c.execute("SELECT * FROM categories WHERE id = ?", (cid,)).fetchone()
        return dict(r) if r else None

def category_by_name(name: str) -> dict | None:
    """Case-insensitive lookup."""
    with conn() as c:
        for r in c.execute("SELECT * FROM categories"):
            if r["name"].casefold() == name.casefold():
                return dict(r)
    return None

def fallback_category() -> dict:
    with conn() as c:
        return dict(c.execute("SELECT * FROM categories WHERE id = ?", (_fallback_id(c),)).fetchone())

def create_category(name: str, description: str) -> dict:
    """Add a shelf just above "Other". Raises DuplicateShelf."""
    with conn() as c:
        _check_name_free(c, name)
        try:
            cid = c.execute(
                "INSERT INTO categories(name, description) VALUES (?, ?) RETURNING id", (name, description)
            ).fetchone()["id"]
        except Exception as exc:
            if _is_unique_violation(exc):
                raise DuplicateShelf(f"There's already a shelf named “{name}”") from exc
            raise
        _write_order(c, [i for i in _category_order(c) if i != cid] + [cid])
        return dict(c.execute("SELECT * FROM categories WHERE id = ?", (cid,)).fetchone())

def update_category(cid: int, name: str | None = None, description: str | None = None,
                    position: int | None = None) -> dict:
    """Rename, describe, or move a shelf to 0-based `position` (clamped; "Other" stays last).

    Raises ShelfNotFound, DuplicateShelf, or ShelfError for changes to "Other" it can't take.
    """
    with conn() as c:
        row = c.execute("SELECT * FROM categories WHERE id = ?", (cid,)).fetchone()
        if not row:
            raise ShelfNotFound(f"No shelf with id {cid}")
        other = _fallback_id(c)
        if name is not None and name != row["name"]:
            if cid == other:
                raise ShelfError(f"“{FALLBACK}” is the fallback shelf and can't be renamed")
            _check_name_free(c, name, exclude_id=cid)
            try:
                c.execute("UPDATE categories SET name = ? WHERE id = ?", (name, cid))
            except Exception as exc:
                if _is_unique_violation(exc):
                    raise DuplicateShelf(f"There's already a shelf named “{name}”") from exc
                raise
        if description is not None:
            c.execute("UPDATE categories SET description = ? WHERE id = ?", (description, cid))
        if position is not None:
            if cid == other:
                raise ShelfError(f"“{FALLBACK}” always stays last and can't be moved")
            ids = [i for i in _category_order(c) if i not in (cid, other)]
            ids.insert(max(0, min(position, len(ids))), cid)
            _write_order(c, ids)
        return dict(c.execute("SELECT * FROM categories WHERE id = ?", (cid,)).fetchone())

def delete_category(cid: int, move_to: int | None = None) -> dict:
    """Move the shelf's items to `move_to` (default "Other", marked as the user's choice), then
    delete it. Returns {"moved": n, "moved_to": shelf}. Raises ShelfNotFound or ShelfError."""
    with conn() as c:
        if not c.execute("SELECT 1 FROM categories WHERE id = ?", (cid,)).fetchone():
            raise ShelfNotFound(f"No shelf with id {cid}")
        other = _fallback_id(c)
        if cid == other:
            raise ShelfError(f"“{FALLBACK}” is the fallback shelf and can't be deleted")
        target = other if move_to is None else move_to
        if target == cid:
            raise ShelfError("Choose a different shelf to move its items to")
        dest = c.execute("SELECT * FROM categories WHERE id = ?", (target,)).fetchone()
        if not dest:
            raise ShelfError(f"No shelf with id {target} to move the items to")
        moved = c.execute(
            "UPDATE bookmarks SET category_id = ?, category_set_by = 'user' WHERE category_id = ?", (target, cid)
        ).rowcount
        c.execute("DELETE FROM categories WHERE id = ?", (cid,))
        _write_order(c, _category_order(c))
        return {"moved": moved, "moved_to": dict(dest)}

def set_category(bid: int, cid: int, set_by: str) -> bool:
    """Put a bookmark on a shelf. Returns False if the bookmark doesn't exist; raises
    ShelfError for an unknown shelf."""
    if set_by not in SET_BY:
        raise ValueError(f"set_by must be one of {SET_BY}")
    with conn() as c:
        if not c.execute("SELECT 1 FROM categories WHERE id = ?", (cid,)).fetchone():
            raise ShelfError(f"No shelf with id {cid}")
        return c.execute(
            "UPDATE bookmarks SET category_id = ?, category_set_by = ? WHERE id = ?", (cid, set_by, bid)
        ).rowcount == 1

def set_ai_category(bid: int, cid: int, from_cid: int | None = None) -> bool:
    """Shelve a bookmark as the AI's choice, unless the user or the digest has shelved it
    (and, with from_cid, only while it's still on that shelf). Returns whether it changed."""
    sql = """UPDATE bookmarks SET category_id = ?, category_set_by = 'ai'
             WHERE id = ? AND (category_set_by IS NULL OR category_set_by = 'ai')"""
    params = [cid, bid]
    if from_cid is not None:
        sql += " AND category_id = ?"
        params.append(from_cid)
    with conn() as c:
        return c.execute(sql, params).rowcount == 1

def resort_candidates(limit: int) -> list[dict]:
    """Newest bookmarks on "Other" that the AI put there (never the user's or the digest's)."""
    with conn() as c:
        return [_item(r) for r in c.execute(
            f"""{ITEM_SELECT} WHERE b.category_id = ? AND b.category_set_by = 'ai'
                ORDER BY b.id DESC LIMIT ?""",
            (_fallback_id(c), max(int(limit), 0)),
        )]

def backfill_candidates(redo: bool = False, limit: int | None = None) -> list[dict]:
    """Bookmarks with no shelf (and with redo, also those the AI shelved), oldest first.
    Never the user's or the digest's choices, and never items still being extracted."""
    where = "b.status <> 'pending' AND (b.category_set_by IS NULL OR b.category_set_by = 'ai')"
    if not redo:
        where += " AND b.category_id IS NULL"
    sql, params = f"{ITEM_SELECT} WHERE {where} ORDER BY b.id", []
    if limit is not None:
        sql += " LIMIT ?"
        params.append(max(int(limit), 0))
    with conn() as c:
        return [_item(r) for r in c.execute(sql, params)]

def save_digest(watchlist: str, picks: list[dict], ranked_by: str | None = None,
                category_id: int | None = None) -> tuple[int, list[tuple[int, bool]]]:
    """Save a digest in one transaction. ranked_by: "ai", "prescore" or "prescore_fallback".

    Each pick has url, platform, title, author, text, note, rank, why. A pick whose URL is
    already bookmarked reuses that row (its note is kept). With category_id, picks go on that
    shelf marked "digest", except bookmarks the user already shelved. Returns
    (digest_id, [(bookmark_id, created), ...]) in pick order.
    """
    saved = []
    with conn() as c:
        digest_id = c.execute(
            "INSERT INTO digests(watchlist, ranked_by) VALUES (?, ?) RETURNING id", (watchlist, ranked_by)
        ).fetchone()["id"]
        for p in picks:
            row = c.execute(
                """INSERT INTO bookmarks(url, platform, title, author, text, note, status)
                   VALUES (?, ?, ?, ?, ?, ?, 'ready')
                   ON CONFLICT(url) DO NOTHING
                   RETURNING id""",
                (p["url"], p["platform"], p["title"], p["author"], p["text"], p["note"]),
            ).fetchone()
            created = row is not None
            bid = row["id"] if created else c.execute(
                "SELECT id FROM bookmarks WHERE url = ?", (p["url"],)
            ).fetchone()["id"]
            if category_id is not None:
                c.execute(
                    """UPDATE bookmarks SET category_id = ?, category_set_by = 'digest'
                       WHERE id = ? AND (category_set_by IS NULL OR category_set_by <> 'user')""",
                    (category_id, bid),
                )
            c.execute(
                """INSERT INTO digest_items(digest_id, bookmark_id, rank, why) VALUES (?, ?, ?, ?)
                   ON CONFLICT(digest_id, bookmark_id) DO NOTHING""",
                (digest_id, bid, p["rank"], p["why"]),
            )
            saved.append((bid, created))
    return digest_id, saved

def latest_digests(watchlist: str | None = None) -> list[dict]:
    """The newest digest per watchlist (or just for `watchlist`), newest first, with ranked items."""
    with conn() as c:
        digests = [dict(r) for r in c.execute(
            """SELECT * FROM digests d
               WHERE d.id = (SELECT MAX(id) FROM digests WHERE watchlist = d.watchlist)
                 AND (CAST(? AS TEXT) IS NULL OR d.watchlist = ?)
               ORDER BY d.run_at DESC, d.id DESC""",
            (watchlist, watchlist),
        )]
        for d in digests:
            d["items"] = [dict(r) for r in c.execute(
                """SELECT di.rank, di.why, b.id, b.title, b.url, b.author
                   FROM digest_items di JOIN bookmarks b ON b.id = di.bookmark_id
                   WHERE di.digest_id = ?
                   ORDER BY di.rank""",
                (d["id"],),
            )]
    return digests

def latest_digest_items(watchlist: str | None = None) -> list[dict]:
    """One row per pick from the newest digest of each watchlist (or just `watchlist`).

    Each row: id (bookmark id), title, url, watchlist, rank, why, run_at; ordered by watchlist, rank.
    """
    rows = [
        {"id": item["id"], "title": item["title"], "url": item["url"], "watchlist": d["watchlist"],
         "rank": item["rank"], "why": item["why"], "run_at": d["run_at"]}
        for d in latest_digests(watchlist)
        for item in d["items"]
    ]
    return sorted(rows, key=lambda r: (r["watchlist"], r["rank"]))
