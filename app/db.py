def database_url() -> str | None:
    return os.environ.get("DATABASE_URL") or None

def is_postgres() -> bool:
    return database_url() is not None

def on_vercel() -> bool:
    return bool(os.environ.get("VERCEL"))

def require_database_on_vercel():
    """Vercel's filesystem is read-only, so there it's Postgres or nothing."""
    if on_vercel() and not is_postgres():
        raise RuntimeError(
            "DATABASE_URL is not set. On Vercel the app needs Postgres (SQLite can't be used "
            "there); add DATABASE_URL in the project's Environment Variables and redeploy."
        )

class _PgConn:
    """psycopg connection that accepts `?` placeholders; `with` commits (or rolls back) and closes."""

    def __init__(self, url: str):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg.types.string import TextLoader
        # prepare_threshold=None: Supabase's transaction pooler can't keep prepared statements.
        self._c = psycopg.connect(url, row_factory=dict_row, prepare_threshold=None)
        # Return timestamps as Postgres's text ("2024-01-02 10:00:00"), the same shape SQLite gives.
        self._c.adapters.register_loader("timestamp", TextLoader)

    def execute(self, sql: str, params=()):
        return self._c.execute(sql.replace("%", "%%").replace("?", "%s"), params)

    def rollback(self):
        self._c.rollback()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return self._c.__exit__(*exc)

def conn():
    if url := database_url():
        return _PgConn(url)
    c = sqlite3.connect(DB_PATH)
    c.row_factory = sqlite3.Row     # rows behave like dicts
    return c

def _utc_text(value: str | None) -> str | None:
    """ISO 8601 -> 'YYYY-MM-DD HH:MM:SS' in UTC, like SQLite's datetime(); None if unparseable."""
    if not value:
        return None
    try:
        dt = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc).replace(tzinfo=None)
    return dt.strftime("%Y-%m-%d %H:%M:%S")

def init(recover_pending: bool = True):
    """Create/migrate tables. recover_pending=False skips the restart cleanup (for other processes)."""
    with conn() as c:
        if is_postgres():
            for stmt in PG_SCHEMA:
                c.execute(stmt)
        else:
            _init_sqlite(c)
        _seed_categories(c)
        if not recover_pending:
            return
        # Background jobs don't survive a restart, so anything still pending
        # (including rows from before extraction existed) can never finish.
        # Mark them failed so they can be retried.
        c.execute(
            """UPDATE bookmarks
               SET status = 'failed', error = 'Extraction did not finish; retry to extract'
               WHERE status = 'pending'"""
        )

def _init_sqlite(c):
    c.execute("""
    CREATE TABLE IF NOT EXISTS categories(
      id INTEGER PRIMARY KEY,
      name TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      position INTEGER NOT NULL DEFAULT 0,
      created_at TEXT DEFAULT (datetime('now'))
    )""")
    c.execute("CREATE UNIQUE INDEX IF NOT EXISTS categories_name_ci ON categories (lower(name))")
    c.execute("""
    CREATE TABLE IF NOT EXISTS bookmarks(
      id INTEGER PRIMARY KEY,
      url TEXT UNIQUE NOT NULL,
      note TEXT,
      created_at TEXT DEFAULT (datetime('now')),
      platform TEXT,
      title TEXT,
      author TEXT,
      text TEXT,
      image TEXT,
      status TEXT NOT NULL DEFAULT 'pending',
      error TEXT
    )""")
    _migrate(c)
    c.execute("""
    CREATE TABLE IF NOT EXISTS summary_runs(
      id INTEGER PRIMARY KEY,
      bookmark_id INTEGER,
      created_at TEXT NOT NULL DEFAULT (datetime('now'))
    )""")
    c.execute("CREATE INDEX IF NOT EXISTS summary_runs_created ON summary_runs (created_at)")
    c.execute("""
    CREATE TABLE IF NOT EXISTS digests(
      id INTEGER PRIMARY KEY,
      watchlist TEXT NOT NULL,
      run_at TEXT NOT NULL DEFAULT (datetime('now')),
      ranked_by TEXT
    )""")
    if "ranked_by" not in {r["name"] for r in c.execute("PRAGMA table_info(digests)")}:
        c.execute("ALTER TABLE digests ADD COLUMN ranked_by TEXT")
    c.execute("""
    CREATE TABLE IF NOT EXISTS digest_items(
      digest_id INTEGER NOT NULL REFERENCES digests(id),
      bookmark_id INTEGER NOT NULL REFERENCES bookmarks(id),
      rank INTEGER NOT NULL,
      why TEXT,
      PRIMARY KEY (digest_id, bookmark_id)
    )""")

def _migrate(c):
    existing = {r["name"] for r in c.execute("PRAGMA table_info(bookmarks)")}
    for name, decl in NEW_COLUMNS.items():
        if name not in existing:
            c.execute(f"ALTER TABLE bookmarks ADD COLUMN {name} {decl}")
    c.execute("CREATE INDEX IF NOT EXISTS bookmarks_category ON bookmarks (category_id)")

def _seed_categories(c):
    """Seed shelves from CATEGORIES_SEED once (empty table only); always keep "Other", last."""
    if c.execute("SELECT 1 FROM categories LIMIT 1").fetchone() is None:
        try:
            seed = json.loads(CATEGORIES_SEED.read_text(encoding="utf-8"))
        except (FileNotFoundError, json.JSONDecodeError) as exc:
            log.error("Couldn't read %s (%s); starting with only %r", CATEGORIES_SEED, exc, FALLBACK)
            seed = []
        for i, s in enumerate(seed):
            # ON CONFLICT: another instance may be seeding at the same moment.
            c.execute(
                "INSERT INTO categories(name, description, position) VALUES (?, ?, ?) ON CONFLICT DO NOTHING",
                (s["name"].strip(), (s.get("description") or "").strip(), i),
            )
    c.execute(
        "INSERT INTO categories(name, description, position) VALUES (?, ?, ?) ON CONFLICT DO NOTHING",
        (FALLBACK, FALLBACK_DESCRIPTION, 1_000_000),
    )
    _write_order(c, _category_order(c))

def _category_order(c) -> list[int]:
    return [r["id"] for r in c.execute("SELECT id FROM categories ORDER BY position, id")]

def _fallback_id(c) -> int:
    return c.execute("SELECT id FROM categories WHERE lower(name) = ?", (FALLBACK.lower(),)).fetchone()["id"]

def _write_order(c, ids: list[int]):
    """Number shelves 0..n in this order, with "Other" moved to the end; writes only changes."""
    other = _fallback_id(c)
    ids = [i for i in ids if i != other] + [other]
    current = {r["id"]: r["position"] for r in c.execute("SELECT id, position FROM categories")}
    for pos, cid in enumerate(ids):
        if current.get(cid) != pos:
            c.execute("UPDATE categories SET position = ? WHERE id = ?", (pos, cid))

def insert(url: str, note: str | None, platform: str,
           title: str | None = None, created_at: str | None = None) -> tuple[int, bool]:
    """Insert a pending bookmark. Returns (id, created); an existing URL only gets its note updated.

    created_at may be any SQLite-parsable time (e.g. ISO 8601); it defaults to now.
    On Postgres it must be ISO 8601; anything else also defaults to now.
    """
    if is_postgres():
        created_sql, created_at = "COALESCE(CAST(? AS TIMESTAMP), now() AT TIME ZONE 'utc')", _utc_text(created_at)
    else:
        created_sql = "COALESCE(datetime(?), datetime('now'))"
    with conn() as c:
        row = c.execute(
            f"""INSERT INTO bookmarks(url, note, platform, title, created_at)
               VALUES (?, ?, ?, ?, {created_sql})
               ON CONFLICT(url) DO NOTHING
               RETURNING id""",
            (url, note, platform, title, created_at),
        ).fetchone()
        if row:
            return row["id"], True
        return c.execute(
            """UPDATE bookmarks SET note = COALESCE(?, note) WHERE url = ?
               RETURNING id""",
            (note, url),
        ).fetchone()["id"], False

def list_pending(limit: int) -> list[dict]:
    """Up to `limit` pending bookmarks, oldest first."""
    with conn() as c:
        return [dict(r) for r in c.execute(
            "SELECT * FROM bookmarks WHERE status = 'pending' ORDER BY id LIMIT ?", (max(int(limit), 0),)
        )]

def url_exists(url: str) -> bool:
    with conn() as c:
        return c.execute("SELECT 1 FROM bookmarks WHERE url = ?", (url,)).fetchone() is not None

def kind_of(platform: str | None) -> str:
    for kind, platforms in KIND_PLATFORMS.items():
        if platform in platforms:
            return kind
    return "article"

def _item(row) -> dict:
    d = dict(row)
    d["kind"] = kind_of(d.get("platform"))
    d["has_summary"] = bool(d.get("has_summary"))
    return d

# Bookmark columns returned by reads. full_text (fetched paper text, possibly very long) and
# the raw summary JSON stay out of lists; get() adds the parsed summary.
ITEM_COLUMNS = ("id", "url", "note", "created_at", "platform", "title", "author", "text", "image",
                "status", "error", "category_id", "category_set_by",
                "summary_source", "summary_model", "summarized_at")
# Bookmarks with their shelf's name as `category` (None when not shelved yet).
ITEM_SELECT = (f"SELECT {', '.join('b.' + col for col in ITEM_COLUMNS)}, cat.name AS category, "
               "CASE WHEN b.summary_json IS NULL THEN 0 ELSE 1 END AS has_summary "
               "FROM bookmarks b LEFT JOIN categories cat ON cat.id = b.category_id")

def get(bid: int):
    """One bookmark, with its parsed AI summary as `summary` (None if it has none)."""
    with conn() as c:
        r = c.execute(f"{ITEM_SELECT} WHERE b.id = ?", (bid,)).fetchone()
        if not r:
            return None
        raw = c.execute("SELECT summary_json FROM bookmarks WHERE id = ?", (bid,)).fetchone()["summary_json"]
    item = _item(r)
    try:
        item["summary"] = json.loads(raw) if raw else None
    except json.JSONDecodeError:
        log.warning("Bookmark %s has an unreadable summary; ignoring it", bid)
        item["summary"], item["has_summary"] = None, False
    return item

def _now_sql() -> str:
    return "(now() AT TIME ZONE 'utc')" if is_postgres() else "datetime('now')"

def get_full_text(bid: int) -> str | None:
    with conn() as c:
        r = c.execute("SELECT full_text FROM bookmarks WHERE id = ?", (bid,)).fetchone()
        return r["full_text"] if r else None

def save_full_text(bid: int, text: str):
    with conn() as c:
        c.execute("UPDATE bookmarks SET full_text = ? WHERE id = ?", (text, bid))

def save_summary(bid: int, summary: dict, source: str, model: str):
    if source not in SUMMARY_SOURCES:
        raise ValueError(f"source must be one of {SUMMARY_SOURCES}")
    with conn() as c:
        c.execute(
            f"""UPDATE bookmarks SET summary_json = ?, summary_source = ?, summary_model = ?,
                       summarized_at = {_now_sql()}
                WHERE id = ?""",
            (json.dumps(summary, ensure_ascii=False), source, model, bid),
        )

def _hour_ago_sql() -> str:
    return "(now() AT TIME ZONE 'utc') - interval '1 hour'" if is_postgres() else "datetime('now', '-1 hour')"

def summary_runs_last_hour() -> tuple[int, str | None]:
    """(model calls in the last hour, the oldest one's time as 'YYYY-MM-DD HH:MM:SS' UTC)."""
    with conn() as c:
        r = c.execute(
            f"SELECT COUNT(*) AS n, MIN(created_at) AS oldest FROM summary_runs WHERE created_at > {_hour_ago_sql()}"
        ).fetchone()
        return r["n"], r["oldest"]

def record_summary_run(bid: int, limit: int) -> bool:
    """Count one summary model call, unless `limit` calls were already made in the last hour."""
    with conn() as c:
        n = c.execute(f"SELECT COUNT(*) AS n FROM summary_runs WHERE created_at > {_hour_ago_sql()}").fetchone()["n"]
        if n >= limit:
            return False
        c.execute("INSERT INTO summary_runs(bookmark_id) VALUES (?)", (bid,))
        return True

